class StreamingManifestTurnDataset(IterableDataset):
    """Turn dataset that streams manifest-listed parquet shards at iteration time.

    The eager dataset remains useful for inspection or small debugging workflows
    that need full JSON fields. Training only needs the pre-encoded feature
    bytes and label metadata, so this avoids materializing every sample before
    the first batch.
    """

    def __init__(
        self,
        manifest_path: str | Path,
        *,
        shuffle_shards: bool = True,
        shuffle_rows: bool = True,
        shuffle_buffer_size: int = 8192,
        include_legal_actions: bool = False,
        include_label_action: bool = False,
        seed: int = 20260423,
        distributed_rank: int = 0,
        distributed_world_size: int = 1,
    ) -> None:
        """执行与函数名对应的业务逻辑。
        
        参数:
            self (Self): 当前对象实例。
            manifest_path (str | Path): 清单文件路径。
            shuffle_shards (bool): 相关数据列表。
            shuffle_rows (bool): 相关数据列表。
            shuffle_buffer_size (int): 函数执行所需的输入参数。
            include_legal_actions (bool): 相关数据列表。
            include_label_action (bool): 函数执行所需的输入参数。
            seed (int): 随机种子。
        
        返回:
            None: 无返回值。
        
        异常:
            无。
        """
        self.manifest_path = Path(manifest_path)
        self.shards = _load_manifest_shards(self.manifest_path, task_name="turn")
        self.total_rows = sum(shard.rows for shard in self.shards)
        self.original_rows = self.total_rows
        self.filtered_rows = 0
        self.shuffle_shards = shuffle_shards
        self.shuffle_rows = shuffle_rows
        self.shuffle_buffer_size = max(0, int(shuffle_buffer_size))
        # 大数据 eval 需要动作 JSON 生成错例报告，但仍不读取更大的 state_json。
        self.include_legal_actions = bool(include_legal_actions)
        self.include_label_action = bool(include_label_action)
        self.seed = int(seed)
        self.distributed_rank = int(distributed_rank)
        self.distributed_world_size = max(1, int(distributed_world_size))
        self._iteration = 0

    def __len__(self) -> int:
        """执行与函数名对应的业务逻辑。
        
        参数:
            self (Self): 当前对象实例。
        
        返回:
            int: 整数结果。
        
        异常:
            无。
        """
        return self.total_rows

    def __iter__(self):
        """执行与函数名对应的业务逻辑。
        
        参数:
            self (Self): 当前对象实例。
        
        返回:
            Iterator[Any]: 逐条生成的迭代结果。
        
        异常:
            无。
        """
        worker_info = get_worker_info()
        if worker_info is None:
            worker_id = 0
            worker_count = 1
            seed_base = self.seed
        else:
            worker_id = int(worker_info.id)
            worker_count = int(worker_info.num_workers)
            seed_base = int(worker_info.seed)

        iteration = self._iteration
        self._iteration += 1
        global_worker_id = self.distributed_rank * worker_count + worker_id
        global_worker_count = self.distributed_world_size * worker_count
        rng = random.Random(seed_base + iteration * 1009 + global_worker_id)

        shard_indices = list(range(global_worker_id, len(self.shards), global_worker_count))
        if self.shuffle_shards:
            rng.shuffle(shard_indices)

        if self.shuffle_rows and self.shuffle_buffer_size > 1:
            yield from _buffered_shuffle(
                _iter_turn_training_rows(
                    self.shards,
                    shard_indices,
                    rng if self.shuffle_rows else None,
                    include_legal_actions=self.include_legal_actions,
                    include_label_action=self.include_label_action,
                ),
                rng=rng,
                buffer_size=self.shuffle_buffer_size,
            )
            return

        for shard_index in shard_indices:
            shard = self.shards[shard_index]
            rows = _load_turn_training_rows(
                shard.path,
                include_legal_actions=self.include_legal_actions,
                include_label_action=self.include_label_action,
            )
            if self.shuffle_rows:
                rng.shuffle(rows)
            yield from rows


