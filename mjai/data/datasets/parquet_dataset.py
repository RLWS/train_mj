def _buffered_shuffle(rows, *, rng: random.Random, buffer_size: int):
    """执行与函数名对应的业务逻辑。
    
    参数:
        rows (list[dict[str, object]]): 数据行列表。
        rng (random.Random): 随机数生成器。
        buffer_size (int): 函数执行所需的输入参数。
    
    返回:
        Iterator[Any]: 逐条生成的迭代结果。
    
    异常:
        无。
    """
    buffer = []
    for row in rows:
        if len(buffer) < buffer_size:
            buffer.append(row)
            continue
        index = rng.randrange(len(buffer))
        yield buffer[index]
        buffer[index] = row
    rng.shuffle(buffer)
    yield from buffer


